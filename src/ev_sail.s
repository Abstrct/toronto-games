    sta s_bestd
    A8
    rts

; A16 = rough distance from the boat to s_tx/s_ty (max + 3/8 min). Returns A16.
dist_target:
    A16
    lda s_tx
    sec
    sbc s_x
    bpl @a
    eor #$FFFF
    inc a
@a:
    sta tmp0
    lda s_ty
    sec
    sbc s_y
    bpl @b
    eor #$FFFF
    inc a
@b:
    sta tmp1
    cmp tmp0
    bcc @c
    ; |dy| is the larger
    lda tmp0
    lsr a
    lsr a
    sta tmp0
    lsr a
    clc
    adc tmp0
    clc
    adc tmp1
    rts
@c:
    lsr a
    lsr a
    sta tmp1
    lsr a
    clc
    adc tmp1
    clc
    adc tmp0
    rts

