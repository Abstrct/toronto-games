; ------------------------------------------------------------------
; finish: base = 250 per leg (1000) + 15 per second left (bumps took 2 s
; each off the clock), bonus = style (graded tight roundings, clean tacks,
; ferry surf, 300 for not a single bump). Didn't finish (out of time, adrift,
; gave up): base = 250 per mark rounded + up to 249 for the part of the next
; leg sailed, at most 999, so any finish beats any DNF; style only pays at
; the line. Never steered: 0. The penalty word is always 0 (nothing is taken
; off: bumps cost time, so trying never scores below sitting still).
; ev_stat: time left, marks rounded, bumps, style points
; ev_break: base, bonus, penalty (base + bonus - penalty = ev_score)
sail_score:
    A16
    stz ev_break
    stz ev_break+2
    stz ev_break+4
    lda s_time
    sta tmp0
    A8
    lda #60
    jsl div16
    A16
    lda tmp0
    sta ev_stat
    lda s_mark
    and #$00FF
    cmp #4
    bcc @m
    lda #3
@m:
    sta ev_stat+2
    lda s_bumps
    and #$00FF
    sta ev_stat+4
    stz ev_stat+6
    A8
    lda ev_giveup
    ora s_adrift
    jne @dnf
    lda s_mark
    cmp #4
    jcc @dnf
    ; style: roundings, tacks (a roll tack pays 250), surf, a clean race
    lda s_tacks
    ldx #PTS_TACK
    jsr mulc
    .a16
    clc
    adc s_tstyle
    sta ev_stat+6
    A8
    lda s_rolls
    ldx #(PTS_ROLL - PTS_TACK)
    jsr mulc
    .a16
    clc
    adc ev_stat+6
    sta ev_stat+6
    A8
    lda s_surf
    ldx #PTS_SURF
    jsr mulc
    .a16
    clc
    adc ev_stat+6
    ldx s_bumps                 ; (a word: the high byte stays 0)
    bne @dirty
    clc
    adc #PTS_CLEAN              ; not a single bump
@dirty:
    sta ev_stat+6
    sta ev_break+2
    A8
    ; base: the legs and the clock
    lda ev_stat
    ldx #PTS_SEC
    jsr mulc
    .a16
    clc
    adc #FINISH_MIN
    sta ev_break
    clc
    adc ev_break+2
    sta ev_score
    A8
    stz ev_fail
    rts
@dnf:
    .a8
    A16
    stz ev_score
    A8
    lda s_steer
    jeq @fail                   ; never touched the helm: nothing
    lda s_mark
    cmp #4
    bcc @legs
    lda #3
@legs:
    ldx #(PTS_LEG / 2)          ; (mulc takes k < 256)
    jsr mulc
    .a16
    asl a
    sta tmp4
    ; progress on the leg in hand: (legd - bestd) * 100 / (legd * 2 / 5), < 250
    lda s_mark
    and #$00FF
    cmp #4
    bcs @nop
    lda s_legd
    sec
    sbc s_bestd
    bcc @nop
    beq @nop
    sta tmp1
    asl a
    asl a                       ; *4
    sta tmp2
    asl a
    asl a
    asl a                       ; *32
    sta tmp3
    asl a                       ; *64
    clc
    adc tmp3                    ; *96
    clc
    adc tmp2                    ; *100
    sta WRDIVL
    lda s_legd                  ; legd * 2 / 5 (= legd * 102 / 256, legd <= 510)
    asl a
    sta tmp3                    ; *2
    asl a
    clc
    adc tmp3
    sta tmp3                    ; *6
    asl a
    asl a
    asl a
    asl a                       ; *96
    clc
    adc tmp3                    ; *102
    xba
    and #$00FF
    bne @d3
    inc a
@d3:
    A8
    sta WRDIVB
    nop
    nop
    nop
    nop
    nop
    nop
    nop
    nop
    A16
    lda RDDIVL
    cmp #(PTS_LEG - 1)
    bcc @addp
    lda #(PTS_LEG - 1)
    bra @addp
@nop:
    lda #$0000
@addp:
    clc
    adc tmp4
    sta ev_break
    sta ev_score
    A8
@fail:
    lda ev_giveup
    beq @t
    lda #$03                    ; gave up
    bra @s
@t:
    lda s_adrift
    beq @tt
    cmp #2
    beq @nh
    lda #$01                    ; adrift: ten seconds getting no closer
    bra @s
@nh:
    lda #$04                    ; adrift: nobody ever steered
    bra @s
@tt:
    lda #$02                    ; out of time
@s:
    sta ev_fail
    rts

; A8 = n, X = k (< 256) -> A16 = n * k  (returns in A16)
mulc:
    sta WRMPYA
    txa
    sta WRMPYB
    nop
    nop
    nop
    nop
    A16
    lda RDMPYL
    rts

