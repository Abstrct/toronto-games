    sbc s_y
    cmp #$8000
    ror a
    bmi @yn
    cmp #LOOK_Y
    bcc @ys
    lda #LOOK_Y
    bra @ys
@yn:
    cmp #($10000 - LOOK_Y)
    bcs @ys
    lda #($10000 - LOOK_Y)
@ys:
    sta tmp3
    A8
    rts

