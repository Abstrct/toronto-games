    sec
    sbc s_head
    beq @hike
    bmi @left
    cmp #(TURN_RATE + 1)
    bcc @snap
    lda s_head
    clc
    adc #TURN_RATE
    sta s_head
    bra @hike
@left:
    cmp #($100 - TURN_RATE)
    bcs @snap
    lda s_head
    sec
    sbc #TURN_RATE
    sta s_head
    bra @hike
