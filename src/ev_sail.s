; notched steering: a tap turns the goal one notch (one boat frame); held, it
; keeps going one notch every REP_NEXT frames after REP_FIRST. The bow swings
; to the goal at TURN_RATE, the same at any speed. Ten seconds without a touch
; of LEFT/RIGHT and the race is over.
steer:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    A8
    bne @held
    stz s_hold
    stz s_hdir
    A16
    inc s_idle
    lda s_idle
    cmp #IDLE_WARN
    bne @nw
    A8
    LDPTR0 str_nudge
    lda #TP_YELLOW
    ldx #120
    jsr hint
    A16
@nw:
    lda s_idle
    cmp #IDLE_CUT
    A8
    bcc @turn
    jsr adrift
    bra @turn
@held:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    xba
    A8
    sta s_cur2                  ; this frame's direction bits (>PAD_LEFT, >PAD_RIGHT)
    lda #1
    sta s_steer
    ldx #$0000
    stx s_idle
    lda s_cur2
    cmp s_hdir                  ; changed hands: a fresh press
    beq @same
    sta s_hdir
    stz s_hold
@same:
    lda s_hold
    beq @notch
    cmp #REP_FIRST
    bcc @count
    lda #(REP_FIRST - REP_NEXT)
    sta s_hold
@notch:
    jsr notch
@count:
    inc s_hold
@turn:
    ; swing the bow toward the goal, the short way round
    lda s_hgoal
    sec
    sbc s_head
    beq @hike
    bmi @left
    cmp #(TURN_RATE + 1)
    bcc @snap
    lda s_head
    clc
    adc #TURN_RATE
    sta s_head
    bra @hike
@left:
    cmp #($100 - TURN_RATE)
    bcs @snap
    lda s_head
    sec
    sbc #TURN_RATE
    sta s_head
    bra @hike
@snap:
    lda s_hgoal
    sta s_head
@hike:
    A16
    lda pad
    and #PAD_A
    A8
    beq @nh
    lda #1
@nh:
    sta s_hike
    rts

; one notch toward the held direction (s_hdir); an off-notch goal (after the
; crew pushes off) snaps to the next notch that way
notch:
    lda s_hdir
    and #>PAD_LEFT
    beq @r
    lda s_hgoal
    dec a
    and #$F0
    sta s_hgoal
    rts
@r:
    lda s_hgoal
    clc
    adc #NOTCH
    and #$F0
    sta s_hgoal
    rts

; nobody at the helm for IDLE_CUT frames: the race is over
adrift:
    lda #1
    sta s_adrift
    lda #ST_FINISH
    sta s_state
    ldx #120
    stx s_timer
    stz s_qhint
    SFX SFX_HORN
    LDPTR0 str_adrift
    lda #TP_RED
    ldx #300
    jmp popup

wind_and_gusts:
    ; wind shifts every few seconds, eases toward the new direction
    A16
    dec s_wtimer
    A8
    bne @ease
    ldx #300
    stx s_wtimer
    lda #40
    jsr ev_range
    sec
    sbc #20
    sta s_wtgt
@ease:
    lda s_tick
    and #$07
    bne @gust
    lda s_wind
    cmp s_wtgt
    beq @gust
    sec
    sbc s_wtgt
    bmi @inc
    dec s_wind
    bra @gust
@inc:
    inc s_wind
@gust:
    A16
    lda s_gust
    beq @nogust
    dec s_gust
    A8
    rts
@nogust:
    dec s_gtimer
    A8
    bne @x
    lda #200
