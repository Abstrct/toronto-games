; a new leg: remember how far there is to go (partial credit if time runs out)
leg_start:
    jsr target_pos
    jsr dist_target
    A16
    cmp #510
    bcc @a
    lda #510
@a:
    cmp #8
    bcs @b
    lda #8
@b:
