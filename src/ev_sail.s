popup_any:
    stx s_popup
    sta s_ppal
    lda s_pnew
    sta s_pprio
    ldx #$0000
    stx s_pon
    ldx ptr0
    stx s_pptr
    lda ptr0+2
    sta s_pptr+2
    lda #4                      ; (the frame that asked has done enough: next one)
    sta s_pend
    rts

; carry set if the coach may talk now: nothing up, a teaching line, its own
; line, or news that has had its moment
coach_free:
    A16
    lda s_popup
    A8
    beq @y
    lda s_pprio
    beq @y
    cmp #2
    beq @y
    bcs @n
    A16
    lda s_pon
    cmp #NEWS_MIN
    A8
    bcs @y
@n:
    clc
    rts
@y:
    sec
    rts

; the callout (or its removal), drawn in the HUD's text slot: panel and
; words in the same frame, so it never flashes empty
pop_draw:
    ldx s_pptr
    stx ptr0
    lda s_pptr+2
    sta ptr0+2
    lda s_pend
    stz s_pend
    cmp #4
    bne @b
    lda #1
    sta s_pend
    rts
@b:
    cmp #1
    beq @box
    jmp pop_clear
@text:
    lda #TXT_WIN
    sta txt_bg
    lda s_ppal
    asl a
    asl a
    ora #$20
    ldx #(CALL_ROW*32)
    jsl txt_print_centre
    stz txt_bg
    rts
@box:
    ldy #$0000
@len:
    lda [ptr0],y
    beq @got
    iny
    bra @len
@got:
    tya
    clc
    adc #4
    sta s_bw                    ; the panel: s_bw wide from column s_bx0
    lda #32
    sec
    sbc s_bw
    lsr a
    sta s_bx0
    ; wipe only what the new panel won't cover (the old one may be wider)
    beq @nl
    sta tmp1
    lda #3
    sta tmp1+1
    stz tmp2
    ldx #(CALL_ROW*32 - 32)
    lda #$20
    jsl txt_fill
@nl:
    lda s_bx0
    clc
    adc s_bw
    sta tmp0
    lda #32
    sec
    sbc tmp0
    beq @nr
    sta tmp1
    lda #3
    sta tmp1+1
    stz tmp2
    lda tmp0
    A16
    and #$00FF
    clc
    adc #(CALL_ROW*32 - 32)
    tax
    A8
    lda #$20
    jsl txt_fill
@nr:
    lda s_bw
    sta tmp1
    lda #3
    sta tmp1+1
    lda s_bx0
    A16
    and #$00FF
    clc
    adc #(CALL_ROW*32 - 32)
    tax
    A8
    lda #$20
    jsl txt_box
    ldx s_pptr                  ; (txt_box took ptr0)
    stx ptr0
    lda s_pptr+2
    sta ptr0+2
    jmp @text

; blank the callout panel
pop_clear:
