    sta s_hold
    bra @count
@same:
    lda s_hold
    beq @notch
    cmp #REP_FIRST
    bcc @count
    lda #(REP_FIRST - REP_NEXT)
    sta s_hold
@notch:
    jsr notch
@count:
    inc s_hold
@turn:
