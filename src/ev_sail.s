    beq @p0
    ldx #MS_PAW1_BASE
    bra @go
@p0:
    ldx #MS_PAW0_BASE
@go:
    stx tmp6
    jsr spr16
    bra @n
@fleck:
    ldx #MS_FLECK_BASE
    stx tmp6
    jsr spr8
    bra @n
@n16:
    A8
@n:
    ldx s_cur
    inx
    inx
    cpx #(NUM_RIP*2)
    bne @r
    rts

; One sprite, straight into the OAM buffer (much cheaper than oam_meta for
; single-piece objects). spr_x/spr_y = centre, tmp6 = tile (9 bits), tmp5 =
; attribute byte. spr16: 16x16, spr8: 8x8. spr_x/spr_y are left alone.
spr16:
    lda #2
    sta s_szbit
    ldx #8
    bra sprc
spr8:
    stz s_szbit
    ldx #4
sprc:
    stx s_tmp
    A16
    lda spr_x
    sec
    sbc s_tmp
    sta s_ox
    clc
    adc #16
    cmp #(256 + 16)
    bcs @skip
    lda spr_y
    sec
    sbc s_tmp
    sta s_oy
    clc
    adc #32
    cmp #(224 + 32)
    bcs @skip
    ldx oam_idx
    cpx #512
    bcs @skip
    A8
    lda s_ox
    sta oam_buf,x
    lda s_oy
    sta oam_buf+1,x
    lda tmp6
    sta oam_buf+2,x
    lda tmp6+1
    and #$01
    ora tmp5
    sta oam_buf+3,x
    ; high table: x bit 8 and the size bit, 2 bits per sprite
    lda s_ox+1
    and #$01
    ora s_szbit
    beq @adv
    sta s_tmp
    stz s_tmp+1
    A16
    txa
    and #$000C
    ora s_tmp
    tay
    txa
    lsr a
    lsr a
    lsr a
    lsr a
    tax
    A8
    lda hi_tab,y
    ora oam_hi,x
    sta oam_hi,x
@adv:
    A16
    lda oam_idx
    clc
    adc #4
    sta oam_idx
@skip:
    A8
    rts

hi_tab:
    .byte $00, $01, $02, $03
    .byte $00, $04, $08, $0C
    .byte $00, $10, $20, $30
    .byte $00, $40, $80, $C0

; ------------------------------------------------------------------
