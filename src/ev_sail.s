    ; she leaves its ring, so it can't sweep her onto it), nor in the last
    ; few px before the next ring: too late to help
    lda s_rjust
    beq @nr
    ldx s_bmark
    A16
    lda f:mark_x,x
    sec
    sbc s_x
    sta tmp0
    lda f:mark_y,x
    sec
    sbc s_y
    sta tmp1
    jsr dist_xy
    cmp #(ROUND_R + 4)
    A8
    jcc @x
@nr:
    A16
    lda s_dist
    cmp #(ROUND_R + 12)
    A8
    bcs @far
    lda s_mark
    cmp #3
    jcc @x
@far:
    jsr coach_free
    jcc @x
    jmp issue_order
@on:
    ldx #$0000
    stx s_offc
    lda s_rjust                 ; just rounded and on course already
    beq @gt
    stz s_rjust
    lda s_mark
    dec a
    asl a
    TAXB
    A16
    lda f:round_lo,x
    sta ptr0
    A8
    lda #^str_round1
    sta ptr0+2
    lda #TP_GREEN
    ldx #45
    jmp popup
