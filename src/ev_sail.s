; notched steering: a tap turns the goal one notch (one boat frame); held, it
; keeps going one notch every REP_NEXT frames after REP_FIRST. The bow swings
; to the goal at TURN_RATE, the same at any speed. Ten seconds without a touch
; of LEFT/RIGHT and the race is over.
steer:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    A8
    bne @held
    stz s_hold
    stz s_hdir
    A16
    inc s_idle
    A8
    ; hands off is fine (a good line is held, not steered); only a helm that
    ; has never been touched at all ends the race
    lda s_steer
    jne @turn
    A16
    lda s_tick
    cmp #HELM_WARN
    bne @hc
    A8
    LDPTR0 str_nudge
    lda #TP_YELLOW
    ldx #150
    jsr popup
    bra @turn
@hc:
    .a16
    cmp #HELM_CUT
    A8
    bcc @turn
    lda #2
    jsr adrift
    bra @turn
@held:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    xba
    A8
    sta s_cur2                  ; this frame's direction bits (>PAD_LEFT, >PAD_RIGHT)
    lda #1
    sta s_steer
    sta s_otch
    ldx #$0000
    stx s_idle
    lda s_cur2
    cmp s_hdir                  ; changed hands: a fresh press
    beq @same
    sta s_hdir
    stz s_hold
    ; aground: a tap the way the coach says and the crew shoves her off
    lda s_gdir
    beq @same
    bmi @gl
    lda s_cur2
    and #>PAD_RIGHT
    bne @push
    bra @same
@gl:
    lda s_cur2
    and #>PAD_LEFT
    beq @same
