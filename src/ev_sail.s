    jsr issue_order             ; the coach says so from the gun
@loop:
    jsl wait_frame
    ; our own end comes first: once the line is crossed (or time's up, or
    ; she's adrift) a give-up from the pause menu can't change the result
    lda s_state
    cmp #ST_SAIL
    beq @sailing
    lda ev_giveup
    beq @run
    stz ev_giveup
    bra @quit
@sailing:
    lda ev_giveup               ; pause menu: give up (scored as a DNF)
    bne @quit
@run:
    jsr sail_update
    lda s_state
    cmp #ST_DONE
    beq @quit
    jsr water_cycle
    jsr sail_draw
    jsr sail_hud
    bra @loop
@quit:
    jsl music_stop
    jsr sail_score
    ; an empty HUD panel and no callout behind the card
    jsr pop_clear
    ldx #$0000
    A16
    lda #$0420                  ; 32 x 4
    sta tmp1
    A8
    lda #HUD_ATTR
    jsl txt_box
    jsl score_card
    ; back to the usual 64x32 BG1 / BG2 maps and backdrop for the next screens
