; Coaching. s_adir is the course to steer (course); the bow diamonds turn
; green on it, and off it the coach gives an order: how many taps.

; -> A8 = taps from the bow's notch to the course to steer, signed (+ = right),
; the short way round; Z set if none
taps_to_course:
    lda s_adir
    sec
    sbc s_hgoal
    clc
    adc #(NOTCH / 2)
    cmp #$80
    ror a
    cmp #$80
    ror a
    cmp #$80
    ror a
    cmp #$80
    ror a
    cmp #$00
    rts

; every frame while racing: the coach. One order at a time: it stands until
; the bow's notch reaches it (then its line says GOOD!, or the second half of
; a long turn follows at once), it lapses (ORDER_T), or the taps go the other
; way; only then can there be another. An order nobody has started on is
; said afresh once the course to steer has moved on (REPLAN_T). After a
; rounding the turn for the next leg waits for the buoy to be abeam
; (round_gate), so it can't sweep her onto it.
coach:
    jsl buoy_watch
    lda s_ord
    cmp #$FF
    jeq @none
    A16
    inc s_ordt
    lda s_ordt
    cmp #ORDER_T
    A8
    bcs @lapse
    lda s_hgoal
    cmp s_ord
    beq @done
    lda s_omd                   ; (on a good course another way before she's
    cmp #3                      ; started on it: done too; not clear of the
    beq @ww                     ; buoy just rounded, though)
    lda s_otch
    bne @ww
    lda s_green
    bne @done
@ww:
    lda s_ord                   ; more taps to go than it asked for: wrong way
    sec
    sbc s_hgoal
    jsr abs8
    lsr a
    lsr a
    lsr a
    lsr a
    cmp s_ordn
    beq @late
    bcc @late
    ; the other way: a tap she'd started before this order went up lands in
    ; its first moments: the order again from where the bow is now
    A16
    lda s_ordt
    cmp #12
    A8
    bcs @lapse
    lda s_omd
    cmp #3
    beq @lapse
    lda s_reiss                 ; (once: after that it's her steering)
    bne @lapse
    lda #$FF
    sta s_ord
    stz s_omode
    jsl issue_order
    lda #1
    sta s_reiss
    rts
@lapse:
    lda #$FF
    sta s_ord
    stz s_split
    stz s_reiss
    lda s_pprio                 ; (its line goes with it)
    cmp #2
    bne @x
    ldx #$0001
    stx s_popup
    rts
@done:
    jsl order_done
    rts
@late:
    ; not started on, and the course to steer has moved: say it afresh
    lda s_otch
    bne @x
    A16
    lda s_ordt
    cmp #REPLAN_T
    A8
    bcc @x
    lda s_adir
    cmp s_ofin
    beq @x
    jsr coach_free
    bcc @x
    lda #$FF
    sta s_ord
    stz s_omode
    jsl issue_order
@x:
    rts
@none:
    lda s_gdir                  ; aground: which way to tap to get off
    beq @afloat
    A16
    lda s_ground
    A8
    bne @agr
    stz s_gdir                  ; (she slid off by herself)
    bra @afloat
@agr:
    lda s_gsaid
    bne @x
    jsr coach_free
    bcc @x
    inc s_gsaid
    jsl buf_new
    LDPTR1 str_agr
    jsl cat
    lda s_gdir
    jsl taps_dir
    LDPTR1 str_bear
    jsl cat
    jsl buf_ptr
    lda #TP_RED
    ldx #GROUND_PUSH
    jmp say_coach
@afloat:
    lda s_rjust                 ; just rounded: the turn for the next leg
    beq @nr
    jsl round_gate
    rts
@nr:
    lda s_green
    bne @on
    A16
    inc s_offc
    lda s_offc
    cmp #COACH_DLY
    A8
    bcs @due
    lda s_urgent                ; (the line runs onto the buoy: at once)
    cmp #1
    bne @x
@due:
    lda s_urgent
