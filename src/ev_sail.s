    ; TACK NOW: boat and arrow both upwind-ish, on opposite sides of the wind
    stz tmp0
    lda s_amode
    bne @ask
    lda s_hgoal
    sec
    sbc s_wind
    sta tmp1
    jsr abs8
    cmp #72
    bcs @ask
    lda s_adir
    sec
    sbc s_wind
    sta tmp2
    eor tmp1
    bpl @ask                    ; same side of the wind
    lda tmp2
    jsr abs8
    cmp #72
    bcs @ask                    ; the arrow says bear away (downwind), not tack
    inc tmp0
@ask:
    lda tmp0
    cmp s_tackon
    sta s_tackon
    beq @x
    lda tmp0
    beq @x
    lda s_tackcd
    bne @x
    lda #120
    sta s_tackcd
    SFX SFX_BLIP
    LDPTR1 str_tack
    jsr taps_to_course
    beq @x
    jsr coach_pre
    lda #TP_YELLOW
    ldx #120
    jsr popup
@x:
    lda s_tackcd
    beq @r
    dec s_tackcd
@r:
    rts

