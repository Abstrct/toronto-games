; a new leg: remember how far there is to go (partial credit if time runs out)
leg_start:
    jsr target_pos
    jsr dist_target
    A16
    cmp #510
    bcc @a
    lda #510
@a:
    cmp #8
    bcs @b
    lda #8
@b:
    sta s_legd
    sta s_bestd
    lda #$7FFF                  ; a new leg: ten seconds' grace (no history)
    ldx #(PROG_N*2 - 2)
@r:
    sta s_ringd,x
    dex
    dex
    bpl @r
    stz s_warned
    A8
    stz s_ringi
    rts

; A16 = rough distance from the boat to s_tx/s_ty (max + 3/8 min). Returns A16.
dist_target:
    A16
    lda s_tx
    sec
    sbc s_x
    bpl @a
    eor #$FFFF
    inc a
@a:
    sta tmp0
    lda s_ty
    sec
    sbc s_y
    bpl @b
    eor #$FFFF
    inc a
@b:
    sta tmp1
    cmp tmp0
    bcc @c
    ; |dy| is the larger
    lda tmp0
    lsr a
    lsr a
    sta tmp0
    lsr a
    clc
    adc tmp0
    clc
    adc tmp1
    rts
@c:
    lsr a
    lsr a
    sta tmp1
    lsr a
    clc
    adc tmp1
