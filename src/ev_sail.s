; ------------------------------------------------------------------
; finish: base = 300 per leg (1200) + 25 per second left, bonus = style
; (200 per tight rounding, 200 per ferry surf), penalty = 50 per bump, but
; never below 1200. Didn't finish (out of time, adrift, gave up): base =
; 300 per leg done + up to 299 for progress on the next one, at most 1199, so
; any finish beats any DNF; style only pays at the line. Never steered: 0.
; ev_stat: time left, buoys, bumps, style points
; ev_break: base, bonus, penalty (base + bonus - penalty = ev_score)
sail_score:
    A16
    stz ev_break
    stz ev_break+2
    stz ev_break+4
    lda s_time
    sta tmp0
    A8
    lda #60
    jsl div16
    A16
    lda tmp0
    sta ev_stat
    lda s_mark
    and #$00FF
    cmp #4
    bcc @m
    lda #3
@m:
    sta ev_stat+2
    lda s_bumps
    and #$00FF
    sta ev_stat+4
    stz ev_stat+6
    A8
    lda ev_giveup
    ora s_adrift
    jne @dnf
    lda s_mark
    cmp #4
    jcc @dnf
    ; style
    lda s_tight
    ldx #PTS_TIGHT
    jsr mulc
    .a16
    sta ev_stat+6
    A8
    lda s_surf
    ldx #PTS_SURF
    jsr mulc
    .a16
    clc
    adc ev_stat+6
    sta ev_stat+6
    sta ev_break+2
    A8
    ; base: the legs and the clock
    lda ev_stat
    ldx #PTS_SEC
    jsr mulc
    .a16
    clc
    adc #FINISH_MIN
    sta ev_break
    ; penalty: bumps, capped so the score stays at FINISH_MIN or more
    clc
    adc ev_break+2
    sec
    sbc #FINISH_MIN
    sta tmp4                    ; most the bumps may take
    A8
    lda ev_stat+4
    ldx #PTS_BUMP
    jsr mulc
    .a16
    cmp tmp4
    bcc @pen
    lda tmp4
@pen:
    sta ev_break+4
    lda ev_break
    clc
    adc ev_break+2
    sec
    sbc ev_break+4
    sta ev_score
    A8
    stz ev_fail
    rts
@dnf:
    .a8
    A16
    stz ev_score
    A8
    lda s_steer
    jeq @fail                   ; never touched the helm: nothing
    lda s_mark
    cmp #4
    bcc @legs
    lda #3
@legs:
    ldx #(PTS_LEG / 4)          ; (mulc takes k < 256)
    jsr mulc
    .a16
    asl a
    asl a
    sta tmp4
    ; progress on the leg in hand: (legd - bestd) * 100 / (legd / 3), < 300
    lda s_mark
    and #$00FF
    cmp #4
    bcs @nop
    lda s_legd
    sec
    sbc s_bestd
    bcc @nop
    beq @nop
    sta tmp1
    asl a
    asl a                       ; *4
    sta tmp2
    asl a
    asl a
    asl a                       ; *32
    sta tmp3
    asl a                       ; *64
    clc
    adc tmp3                    ; *96
    clc
    adc tmp2                    ; *100
    sta WRDIVL
    lda s_legd                  ; legd / 3 (= legd * 85 / 256, legd <= 510)
    sta tmp3
    asl a
    asl a
    clc
    adc tmp3                    ; *5
    sta tmp3
    asl a
    asl a
    asl a
    asl a                       ; *80
    clc
    adc tmp3                    ; *85
    xba
    and #$00FF
    bne @d3
    inc a
@d3:
    A8
    sta WRDIVB
    nop
    nop
    nop
    nop
    nop
    nop
    nop
    nop
    A16
    lda RDDIVL
    cmp #(PTS_LEG - 1)
    bcc @addp
    lda #(PTS_LEG - 1)
    bra @addp
@nop:
    lda #$0000
@addp:
    clc
    adc tmp4
    sta ev_score
    sta ev_break
    A8
@fail:
    lda ev_giveup
    beq @t
    lda #$03                    ; gave up
    bra @s
@t:
    lda s_adrift
    beq @tt
    lda #$01                    ; adrift: nobody steering
    bra @s
@tt:
    lda #$02                    ; out of time
@s:
    sta ev_fail
    rts

; A8 = n, X = k (< 256) -> A16 = n * k  (returns in A16)
mulc:
    sta WRMPYA
    txa
    sta WRMPYB
    nop
    nop
    nop
    nop
    A16
    lda RDMPYL
    rts

