; notched steering: a tap turns the goal one notch (one boat frame); held, it
; keeps going one notch every REP_NEXT frames after REP_FIRST. The bow swings
; to the goal at TURN_RATE, the same at any speed. Ten seconds without a touch
; of LEFT/RIGHT and the race is over.
steer:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    A8
    bne @held
    stz s_hold
    stz s_hdir
    ; hands off is fine (a good line is held, not steered); only a helm that
    ; has never been touched at all ends the race
    lda s_steer
    bne @turn
    A16
    lda s_tick
    cmp #HELM_WARN
    bne @hc
    A8
    LDPTR0 str_nudge
    lda #TP_YELLOW
    ldx #150
    jsr popup
    bra @turn
@hc:
    .a16
    cmp #HELM_CUT
    A8
    bcc @turn
    lda #2
    jsr adrift
    bra @turn
@held:
    A16
    lda pad
    and #(PAD_LEFT | PAD_RIGHT)
    xba
    A8
    sta s_cur2                  ; this frame's direction bits (>PAD_LEFT, >PAD_RIGHT)
    lda #1
    sta s_steer
    lda s_cur2
    cmp s_hdir                  ; changed hands: a fresh press
    beq @same
    sta s_hdir
    stz s_hold
@same:
    lda s_hold
    beq @notch
    cmp #REP_FIRST
    bcc @count
    lda #(REP_FIRST - REP_NEXT)
    sta s_hold
@notch:
    jsr notch
@count:
    inc s_hold
@turn:
    ; swing the bow toward the goal, the short way round
    lda s_hgoal
    sec
    sbc s_head
    beq @hike
    bmi @left
    cmp #(TURN_RATE + 1)
    bcc @snap
    lda s_head
    clc
    adc #TURN_RATE
    sta s_head
    bra @hike
@left:
    cmp #($100 - TURN_RATE)
    bcs @snap
    lda s_head
    sec
    sbc #TURN_RATE
    sta s_head
    bra @hike
@snap:
    lda s_hgoal
    sta s_head
@hike:
    A16
    lda pad
    and #PAD_A
    A8
    beq @nh
    lda #1
@nh:
    sta s_hike
    rts

; one notch toward the held direction (s_hdir); an off-notch goal (after the
; crew pushes off) snaps to the next notch that way
notch:
    lda s_hdir
    and #>PAD_LEFT
    beq @r
    lda s_hgoal
    dec a
    and #$F0
    sta s_hgoal
    rts
@r:
    lda s_hgoal
    clc
    adc #NOTCH
    and #$F0
    sta s_hgoal
    rts

