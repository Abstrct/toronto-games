; ptr0 = message (28 characters at most), A = text palette, X = frames on
; screen. Callouts sit in a solid 3-row panel (as Tallboy's do), so they read
; over water, land and sprites alike: just under the HUD, where they hide the
; least of the course ahead.
CALL_ROW = 5
popup:
    pha
    lda #1
    sta s_pprio
    pla
popup_any:
    stx s_popup
    stz s_irmsg
    sta s_ppal
    ldx ptr0
    stx s_pptr
    lda ptr0+2
    sta s_pptr+2
    lda #4                      ; (the frame that asked has done enough: next one)
    sta s_pend
    rts

; the callout (or its removal), drawn in the HUD's text slot so a frame never
; does both: the panel one frame, the words the next
pop_draw:
    ldx s_pptr
    stx ptr0
    lda s_pptr+2
    sta ptr0+2
    lda s_pend
    stz s_pend
    cmp #4
    bne @b
    lda #1
    sta s_pend
    rts
@b:
    cmp #1
    beq @box
    cmp #3
    beq @text
    jmp pop_clear
@text:
    lda #TXT_WIN
    sta txt_bg
    lda s_ppal
    asl a
    asl a
    ora #$20
    ldx #(CALL_ROW*32)
    jsl txt_print_centre
    stz txt_bg
    rts
@box:
    lda #3                      ; the words next frame
    sta s_pend
    jsr pop_clear
    ldy #$0000
@len:
    lda [ptr0],y
    beq @got
    iny
    bra @len
@got:
    tya
    clc
    adc #4
    sta tmp1
    lda #3
    sta tmp1+1
    lda #32
    sec
    sbc tmp1
    lsr a
    A16
    and #$00FF
    clc
    adc #(CALL_ROW*32 - 32)
    tax
    A8
    lda #$20
    jsl txt_box
    rts

; blank the callout panel
pop_clear:
    ldx #(CALL_ROW*32 - 32)
    A16
    lda #$0320
    sta tmp1
    A8
    stz tmp2
    lda #$20
    jsl txt_fill
    rts

