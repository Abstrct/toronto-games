    cmp #$8000
    ror a
    bmi @xn
    cmp #LOOK_X
    bcc @xs
    lda #LOOK_X
    bra @xs
@xn:
    cmp #($10000 - LOOK_X)
    bcs @xs
    lda #($10000 - LOOK_X)
@xs:
